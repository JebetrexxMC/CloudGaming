#!/usr/bin/env bash
# Deploy a Windows app to a Linux VPS with CloudMorph (Wine + WebRTC, plays in the browser).
#   ./deploy.sh <vps-ip> <local-game-dir> <exe-name> [window-title]
set -euo pipefail
IP="${1:?vps ip}"; GAME_DIR="${2:?local game folder}"; EXE="${3:?exe name, e.g. Game.exe}"; TITLE="${4:-$EXE}"
REPO="${CLOUDMORPH_REPO:-https://github.com/giongto35/cloud-morph}"
WORK="$(mktemp -d)"
git clone --depth 1 "$REPO" "$WORK/cloud-morph"
# Same layout as upstream's script/example/<game>/: config.yaml + apps/<name>/
APP_DIR="$WORK/cloud-morph/script/example/cloudgaming"
mkdir -p "$APP_DIR/apps"
cp -r "$GAME_DIR" "$APP_DIR/apps/game"
cat > "$APP_DIR/config.yaml" <<YAML
# generated by CloudGaming/cloud-morph/deploy.sh
path: apps/game
appFile: "${EXE}"
windowTitle: "${TITLE}"
pageTitle: "CloudGaming - ${TITLE}"
appName: "CloudGaming-${EXE%.*}"
appMode: collaborative
hasChat: true
virtualize: false
videoCodec: h264
screenWidth: 1280
screenHeight: 720
isWindowMode: true
YAML
cd "$APP_DIR"
chmod +x ../../setup_remote.sh
../../setup_remote.sh "$IP"
echo "Open http://${IP} (port 80 is redirected to 8080)"
